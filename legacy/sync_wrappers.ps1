# sync_wrappers.ps1 — Đồng bộ app.js + index.css vào wrapper .html
# (Apps Script HtmlService chỉ serve được file .html, nên cần wrapper.)

$ErrorActionPreference = "Stop"

function Sync-Wrapper {
    param([string]$SrcPath, [string]$WrapperPath, [string]$Comment)

    if (-not (Test-Path $SrcPath)) {
        Write-Host "[SKIP] $SrcPath not found" -ForegroundColor Yellow
        return
    }

    $content = Get-Content $SrcPath -Raw -Encoding UTF8
    # Escape backtick (template literal) nếu cần — wrapper chỉ cần escape ` nếu dùng <?!= ... ?>
    # Nhưng <?!= ?> in raw, nên cần escape \ thành \\, và có thể phải escape backtick.
    # Đơn giản: dùng cách base64 encode an toàn nhất.

    $bytes = [System.Text.Encoding]::UTF8.GetBytes($content)
    $b64 = [Convert]::ToBase64String($bytes)

    $wrapper = @"
<?!= '// Auto-generated by sync_wrappers.ps1 - DO NOT EDIT.
$Comment
const _src_b64 = "$b64";
// Decode base64 -> UTF8 string
function _b64ToUtf8(b64) {
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new TextDecoder("utf-8").decode(bytes);
}
const _src = _b64ToUtf8(_src_b64);
?>${'$'}{_src}
"@
    Set-Content -Path $WrapperPath -Value $wrapper -Encoding UTF8 -NoNewline
    Write-Host "[OK] $WrapperPath synced" -ForegroundColor Green
}

Sync-Wrapper -SrcPath "app.js" -WrapperPath "app_js.html" -Comment "// app.js (frontend logic)"
Sync-Wrapper -SrcPath "index.css" -WrapperPath "index_css.html" -Comment "// index.css (frontend styles)"

Write-Host "`n[ALL WRAPPERS SYNCED]" -ForegroundColor Cyan